-- ============================================================================
-- V010: разделение владения файлом и физического содержимого
--
-- Было: mf_files.sha256 unique — одна строка на уникальное содержимое.
-- Из-за этого при совпадении SHA-256 второй загрузивший получал строку
-- ПЕРВОГО: его квота не росла, имя файла показывалось чужое, а удаление
-- владельцем сносило запись вместе с вложениями всех остальных
-- (on delete cascade в ms_task_files и ms_task_comment_files).
--
-- Стало: mf_files — запись владения, строк с одним sha256 может быть много.
-- Физический объект по-прежнему один (ключ storage_key = xx/sha256) и
-- удаляется, только когда на него не осталось ни одной записи владения.
-- Квота считается по записям владения и потому становится честной.
--
-- Expand/contract: снятие ограничения и добавление индексов данные не трогают,
-- существующие строки остаются валидными.
-- ============================================================================

alter table mf_files drop constraint if exists mf_files_sha256_key;

-- Поиск существующего физического объекта по содержимому и проверка
-- «остались ли ещё владельцы» перед удалением с диска.
create index if not exists mf_files_sha256_idx on mf_files (sha256);

-- Один и тот же пользователь не может завести две записи владения на одно
-- содержимое: повторная загрузка того же файла возвращает прежнюю запись и
-- не списывает квоту дважды. Частичный, потому что created_by допускает null
-- (файлы системного происхождения).
create unique index if not exists mf_files_owner_sha256_uidx
    on mf_files (created_by, sha256)
    where created_by is not null;

comment on column mf_files.sha256 is
    'SHA-256 содержимого. НЕ уникален: одно содержимое может принадлежать разным пользователям';
comment on column mf_files.created_by is
    'Владелец записи. Квота и права на удаление считаются по нему';
